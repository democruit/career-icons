function origin(name, part, effect) {
  return (
    pivots[`${name}/${part}`] ??
    {
      flap: "50% 0%",
      door: "0% 50%",
      tap: "0% 100%",
      flag: "0% 50%",
      ring: "50% 0%",
      cradle: "50% 0%",
    }[effect] ??
    "50% 50%"
  );
}
function keyframes(name, frames, loop) {
  const entries = frames.map(([at, css]) => [
    `${loop && at !== 100 ? Number((at / 3).toFixed(4)) : at}%`,
    css,
  ]);
  if (loop) entries.splice(-1, 0, ["33.3333%", frames.at(-1)[1]]);
  return `@keyframes ${name}{${entries.map(([at, css]) => `${at}{${css}}`).join("")}}`;
}
export function generateAnimationsCss() {
  const rules = [
    "/* Generated by scripts/animations.mjs. Opt-in; 560ms cycles, 1120ms loop pause. */",
    "@media (prefers-reduced-motion:no-preference){",
  ];
  for (const [name, { parts }] of Object.entries(animationPlan)) {
    if (parts.length) {
      const scope = `.ci-${name}`;
      const hover = `${scope}[data-ci-animate="hover"]:is(:hover,:focus-visible),.ci-hover:is(:hover,:focus-visible,:has(:focus-visible)) ${scope}[data-ci-animate="hover"]`;
      const targets = (suffix) =>
        hover
          .split(",.ci-hover")
          .map((selector, index) => `${index ? ".ci-hover" : ""}${selector} > ${suffix}`)
          .join(",");
      rules.push(`${targets(".ci-rest")}{animation:ci-rest-frame ${hoverDuration}ms step-end 1}`);
      rules.push(
        `${targets(".ci-motion")}{display:inline;visibility:hidden;animation:ci-motion-frame ${hoverDuration}ms step-end 1}`,
      );
      rules.push(
        `${scope}[data-ci-animate="always"] > .ci-rest{animation:ci-rest-frame-loop ${loopDuration}ms step-end infinite}`,
      );
      rules.push(
        `${scope}[data-ci-animate="always"] > .ci-motion{display:inline;visibility:hidden;animation:ci-motion-frame-loop ${loopDuration}ms step-end infinite}`,
      );
    }
    for (const { part, effect } of parts) {
      const frames = effects[effect];
      if (!frames) throw new Error(`${name}: unknown effect ${effect}`);
      const key = `ci-${name}-${part}`;
      const scope = `.ci-${name}`;
      const target = `.ci-part-${part}`;
      const hover = `${scope}[data-ci-animate="hover"]:is(:hover,:focus-visible) ${target},.ci-hover:is(:hover,:focus-visible,:has(:focus-visible)) ${scope}[data-ci-animate="hover"] ${target}`;
      const common = `transform-box:fill-box;transform-origin:${origin(name, part, effect)};animation-timing-function:cubic-bezier(.22,.61,.36,1)`;
      // No fill mode: cancelling a hover/focus cycle immediately restores all original attributes.
      rules.push(
        `${hover}{${common};animation-name:${key};animation-duration:${hoverDuration}ms;animation-iteration-count:1}`,
      );
      rules.push(
        `${scope}[data-ci-animate="always"] ${target}{${common};animation-name:${key}-loop;animation-duration:${loopDuration}ms;animation-iteration-count:infinite}`,
      );
      rules.push(keyframes(key, frames, false), keyframes(`${key}-loop`, frames, true));
    }
  }
  rules.push(
    "@keyframes ci-rest-frame{0%{visibility:visible}1%{visibility:hidden}99%,100%{visibility:visible}}",
    "@keyframes ci-motion-frame{0%{visibility:hidden}1%{visibility:visible}99%,100%{visibility:hidden}}",
    "@keyframes ci-rest-frame-loop{0%{visibility:visible}0.3333%{visibility:hidden}33%,100%{visibility:visible}}",
    "@keyframes ci-motion-frame-loop{0%{visibility:hidden}0.3333%{visibility:visible}33%,100%{visibility:hidden}}",
    "}",
    "@media (prefers-reduced-motion:reduce){[data-ci-animate] [data-ci-part]{animation:none!important}}",
  );
  return `${rules.join("\n")}\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  await writeFile(new URL("../src/animations.css", import.meta.url), generateAnimationsCss());
}
